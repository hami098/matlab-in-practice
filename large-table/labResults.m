function columns = labResults(count, catalog, newest, span)
tests = catalog.tests;
means = [tests.mean];
spreads = [tests.spread];
lows = [tests.low];
highs = [tests.high];
specimens = [tests.specimen];
waits = [180 60 25];
patient = uint32(randi(1e6, count, 1));
if span > 0
    collected = int32(sort(randi([newest - span, newest], count, 1)));
else
    collected = repmat(int32(newest), count, 1);
end
test = randi(numel(tests), count, 1);
value = single(abs(means(test)' + spreads(test)' .* randn(count, 1)));
priority = 1 + sum(rand(count, 1) > [0.7 0.9], 2);
columns = struct( ...
    patient=patient, ...
    collected=collected, ...
    value=value, ...
    turnaround=uint16(min(65535, round(15 + waits(priority)' .* -log(rand(count, 1))))), ...
    age=uint8(18 + mod(double(patient) * 7919, 78)), ...
    sex=uint8(1 + mod(patient, 2)), ...
    department=uint8(randi(numel(catalog.categories.department), count, 1)), ...
    priority=uint8(priority), ...
    test=uint8(test), ...
    specimen=uint8(specimens(test))', ...
    flag=uint8(1 + (value < lows(test)') + 2 * (value > highs(test)')), ...
    status=uint8(1 + sum(rand(count, 1) > [0.9 0.98], 2)), ...
    analyzer=uint8(randi(numel(catalog.categories.analyzer), count, 1)));
end
